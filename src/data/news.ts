function iso(daysAgo: number, h: number, m: number): string {
  const now = new Date();
  const d = new Date(now.getTime() - daysAgo * 86400000);
  d.setHours(h, m, 0, 0);
  // Never let seed data land in the future relative to the real clock — a
  // freshly-ingested article (timestamped with the actual "now") must always
  // sort as the most recent item, regardless of what wall-clock time the demo
  // happens to be viewed at.
  if (d.getTime() > now.getTime()) {
    d.setTime(now.getTime() - (daysAgo * 86400000 + 60000));
  }
  return d.toISOString();
}

